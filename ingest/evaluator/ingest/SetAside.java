package evaluator.ingest;

import java.nio.file.FileSystems;
import java.nio.file.Path;
import java.nio.file.PathMatcher;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Set;

/**
 * Why a source file is not the applicant's own work to count: vendored (someone else's code, copied
 * in) or generated (written by a tool). Read from the path, the file's name, its first lines and the
 * repository's own `.gitattributes`; never from running anything (E-013).
 */
// Decision: E-025
final class SetAside {
    private static final Set<String> VENDORED_FOLDERS = Set.of("node_modules", "vendor", "vendored", "third_party", "third-party",
            "bower_components", ".venv", "venv", "site-packages");
    private static final Set<String> GENERATED_FOLDERS = Set.of("build", "dist", "out", "target", ".next", ".nuxt",
            "generated", "__generated__", "coverage");
    private static final List<String> GENERATED_ENDINGS = List.of(".min.js", ".pb.go", "_pb2.py", "_pb2_grpc.py", ".g.dart",
            ".designer.cs", ".generated.ts", ".generated.js", ".generated.cs");
    private static final List<String> GENERATED_MARKS = List.of("@generated", "code generated", "do not edit", "auto-generated", "autogenerated");
    static final int HEAD_LINES = 5;

    /** One `.gitattributes` line that marks files vendored or generated. */
    record Attribute(PathMatcher matcher, boolean anchored, String pattern, String marks) {}

    private final List<Attribute> attributes;

    SetAside(String gitattributes) {
        this.attributes = attributes(gitattributes == null ? "" : gitattributes);
    }

    /** Why the file is set aside ("vendored: folder vendor/"), or null when it is the applicant's to count. */
    String reason(String path, List<String> head) {
        String reason = byFolder(path);
        if (reason == null) reason = byAttributes(path);
        if (reason == null) reason = byName(path);
        return reason != null ? reason : byHeader(head);
    }

    private static String byFolder(String path) {
        String[] parts = path.split("/");
        for (int i = 0; i < parts.length - 1; i++) {
            if (VENDORED_FOLDERS.contains(parts[i])) return "vendored: folder " + parts[i] + "/";
            if (GENERATED_FOLDERS.contains(parts[i])) return "generated: folder " + parts[i] + "/";
        }
        return null;
    }

    private String byAttributes(String path) {
        String name = path.substring(path.lastIndexOf('/') + 1);
        for (Attribute a : attributes) {
            if (a.matcher().matches(Path.of(a.anchored() ? path : name))) return a.marks() + ": .gitattributes " + a.pattern();
        }
        return null;
    }

    private static String byName(String path) {
        for (String ending : GENERATED_ENDINGS) if (path.endsWith(ending)) return "generated: name *" + ending;
        return null;
    }

    private static String byHeader(List<String> head) {
        for (String line : head.subList(0, Math.min(HEAD_LINES, head.size()))) {
            String lower = line.toLowerCase(Locale.ROOT);
            for (String mark : GENERATED_MARKS) if (lower.contains(mark)) return "generated: header \"" + mark + "\"";
        }
        return null;
    }

    /**
     * The lines of a `.gitattributes` that set linguist-vendored or linguist-generated (and not to false).
     * A pattern with no slash matches a file's name at any depth; one with a slash, the path from the root.
     */
    private static List<Attribute> attributes(String text) {
        List<Attribute> found = new ArrayList<>();
        for (String line : text.lines().toList()) {
            String[] fields = line.trim().split("\\s+");
            if (fields.length < 2 || fields[0].startsWith("#")) continue;
            String marks = marks(fields);
            if (marks == null) continue;
            String pattern = fields[0].startsWith("/") ? fields[0].substring(1) : fields[0];
            boolean anchored = fields[0].contains("/");
            found.add(new Attribute(FileSystems.getDefault().getPathMatcher("glob:" + pattern), anchored, fields[0], marks));
        }
        return found;
    }

    private static String marks(String[] fields) {
        for (int i = 1; i < fields.length; i++) {
            if (fields[i].equals("linguist-vendored") || fields[i].equals("linguist-vendored=true")) return "vendored";
            if (fields[i].equals("linguist-generated") || fields[i].equals("linguist-generated=true")) return "generated";
        }
        return null;
    }
}
