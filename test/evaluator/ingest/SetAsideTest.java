package evaluator.ingest;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

import java.util.List;
import org.junit.jupiter.api.Test;

class SetAsideTest {
    private static final SetAside NONE = new SetAside("");

    @Test
    void aFolderOnlyCountsAsAFolder() {
        assertEquals("generated: folder build/", NONE.reason("app/build/x.js", List.of()));
        assertNull(NONE.reason("src/build.js", List.of()));
        assertNull(NONE.reason("vendor", List.of()));
    }

    @Test
    void aHeaderMarkCountsInTheFirstLinesOnly() {
        assertEquals("generated: header \"do not edit\"", NONE.reason("a.go", List.of("// x", "// DO NOT EDIT")));
        assertNull(NONE.reason("a.go", List.of("1", "2", "3", "4", "5", "// Code generated by x")));
    }

    @Test
    void gitattributesPatternsAreAnchoredOnlyWithASlash() {
        SetAside rules = new SetAside("""
                # comment linguist-vendored
                *.gen.py linguist-generated
                /lib/** linguist-vendored=true
                keep.py linguist-vendored=false
                docs/*.js -linguist-generated
                """);
        assertEquals("generated: .gitattributes *.gen.py", rules.reason("deep/down/x.gen.py", List.of()));
        assertEquals("vendored: .gitattributes /lib/**", rules.reason("lib/a/b.py", List.of()));
        assertNull(rules.reason("src/lib/b.py", List.of()));
        assertNull(rules.reason("keep.py", List.of()));
        assertNull(rules.reason("docs/a.js", List.of()));
    }

    @Test
    void theLanguageIsTheEndings() {
        assertEquals("TypeScript", Languages.of("a/b.tsx"));
        assertEquals("Python", Languages.of("A.PY"));
        assertNull(Languages.of("Makefile"));
        assertNull(Languages.of(".py"));
        assertNull(Languages.of("notes.md"));
    }
}
